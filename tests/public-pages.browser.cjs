const assert = require('node:assert/strict')
const { chromium } = require(process.env.ECOPIN_PLAYWRIGHT_PATH || 'playwright')
const baseUrl = process.env.ECOPIN_TEST_URL || 'http://localhost:4001'

async function run() {
  const browser = await chromium.launch({ headless: true, ...(process.env.ECOPIN_CHROMIUM_PATH ? { executablePath: process.env.ECOPIN_CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const fixture = [{ id: 'reviewed', title: 'Reviewed waste concern', description: 'Waste collection requested near the neighborhood street.', validation_status: 'approved', latitude: 14.5802, longitude: 121.085, issue_type: 'waste', status: 'in_progress', location_precision: 'exact', created_at: '2026-10-12T10:00:00Z' }, { id: 'pending', title: 'Hidden pending concern', validation_status: 'pending', latitude: 14.58, longitude: 121.085, issue_type: 'waste' }]
  await page.route('**/rest/v1/**', route => {
    const url = new URL(route.request().url())
    const id = url.searchParams.get('id')?.replace(/^eq\./, '')
    const rows = id ? fixture.filter(report => report.id === id) : fixture
    return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(url.pathname.includes('public_reports') ? rows : []) })
  })
  await page.route('**/api/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }))
  await page.route('**/api/reports/batch-evidence', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ reviewed: [{ resource_type: 'image', url: `${baseUrl}/images/community/street-cleanup.jpg` }] }) }))
  try {
    await page.goto(`${baseUrl}/auth`)
    await page.getByRole('heading', { name: 'Welcome back.' }).waitFor()
    assert.equal(await page.locator('main h1, main h2').first().evaluate(heading => heading.tagName), 'H1')
    assert.equal(await page.getByRole('navigation').count(), 0)
    assert.equal(await page.getByRole('link', { name: 'Back to EcoPin' }).getAttribute('href'), '/')
    await page.getByLabel('Email address').fill('person@example.test')
    await page.getByLabel('Password', { exact: true }).fill('synthetic-password')
    await page.getByRole('button', { name: 'Show password' }).click()
    assert.equal(await page.getByLabel('Password', { exact: true }).getAttribute('type'), 'text')
    await page.getByRole('button', { name: 'Hide password' }).click()
    await page.route('**/api/auth/login', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: 'Email or password is incorrect.' }) }))
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Email or password is incorrect.' }).waitFor()
    await page.unroute('**/api/auth/login')
    await page.route('**/api/auth/login', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ token: 'synthetic-test-token', user: { role: 'citizen' } }) }))
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'authorized personnel' }).waitFor()
    assert.equal(await page.evaluate(() => localStorage.getItem('authToken')), null)
    await page.unroute('**/api/auth/login')
    await page.route('**/api/auth/login', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ token: 'synthetic-test-token', user: { role: 'field_crew' } }) }))
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Field crews sign in' }).waitFor()
    assert.equal(await page.evaluate(() => localStorage.getItem('authToken')), null)
    for (const width of [320, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Login overflow at ${width}`)
      if (width === 320 && process.env.ECOPIN_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.ECOPIN_SCREENSHOT_DIR}/login-mobile.png`, fullPage: true })
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Switch to dark mode' }).click()
    assert.equal(await page.getByLabel('Email address').evaluate(input => getComputedStyle(input).color), 'rgb(245, 245, 245)')
    if (process.env.ECOPIN_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.ECOPIN_SCREENSHOT_DIR}/login-dark.png`, fullPage: true })
    await page.goto(`${baseUrl}/map?report=reviewed`)
    await page.getByRole('heading', { name: 'Explore Pasig', exact: true }).waitFor()
    assert.equal(new URL(page.url()).pathname, '/explore')
    assert.equal(new URL(page.url()).searchParams.get('report'), 'reviewed')
    await page.getByRole('button', { name: 'Gallery view', exact: true }).click()
    assert.equal(new URL(page.url()).searchParams.get('view'), 'gallery')
    assert.equal(await page.getByRole('button', { name: 'Gallery view', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.goBack()
    assert.equal(await page.getByRole('button', { name: 'Map view', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.goto(`${baseUrl}/gallery`)
    await page.getByRole('heading', { name: 'Explore Pasig', exact: true }).waitFor()
    assert.equal(new URL(page.url()).pathname, '/explore')
    assert.equal(new URL(page.url()).searchParams.get('view'), 'gallery')
    for (const width of [320, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Gallery overflow at ${width}`)
      if (width === 320 && process.env.ECOPIN_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.ECOPIN_SCREENSHOT_DIR}/gallery-mobile.png` })
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    if (process.env.ECOPIN_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.ECOPIN_SCREENSHOT_DIR}/explore-gallery.png` })
    await page.getByRole('button', { name: 'Photos', exact: true }).click()
    await page.getByRole('dialog', { name: 'Report photos' }).waitFor()
    await page.keyboard.press('Tab')
    assert.equal(await page.evaluate(() => Boolean(document.activeElement.closest('[role="dialog"]'))), true)
    await page.keyboard.press('Escape')
    await page.getByRole('dialog', { name: 'Report photos' }).waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), 'Photos')
    await page.getByRole('button', { name: 'Map view', exact: true }).click()
    await page.locator('.leaflet-marker-icon').first().waitFor()
    await page.waitForFunction(() => document.querySelector('.leaflet-marker-icon img')?.src.includes('/images/community/street-cleanup.jpg'))
    assert.equal(await page.getByText('Hidden pending concern', { exact: true }).count(), 0)
    await page.locator('.leaflet-marker-icon').first().click()
    await page.locator('.leaflet-popup').getByText('Status: in progress').waitFor()
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.leaflet-popup')).opacity === '1')
    assert.equal(await page.locator('.leaflet-popup-content').getByRole('button', { name: 'View report' }).evaluate(button => getComputedStyle(button).color), 'rgb(130, 182, 255)')
    if (process.env.ECOPIN_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.ECOPIN_SCREENSHOT_DIR}/explore-map-dark.png` })
    await page.getByRole('button', { name: 'Gallery view', exact: true }).click()
    await page.getByRole('button', { name: 'On Map', exact: true }).click()
    assert.equal(new URL(page.url()).searchParams.get('view'), null)
    await page.getByRole('button', { name: 'Map view', exact: true }).waitFor()
    await page.goto(baseUrl)
    assert.equal(await page.getByRole('link', { name: 'Explore the map', exact: true }).getAttribute('href'), '/explore')
    assert.equal(await page.getByRole('link', { name: 'Browse gallery', exact: true }).getAttribute('href'), '/explore?view=gallery')
    assert.equal(await page.locator('a[href="/map"], a[href="/gallery"]').count(), 0)
    await page.locator('.leaflet-marker-icon').first().waitFor()
    await page.locator('.leaflet-marker-icon').first().click()
    await page.locator('.leaflet-popup').getByText('Status: in progress').waitFor()
    assert.equal(await page.locator('.leaflet-popup-content a').evaluate(link => getComputedStyle(link).color), 'rgb(130, 182, 255)')
    assert.equal(await page.locator('.leaflet-popup-content a').getAttribute('href'), '/explore?report=reviewed')
    await page.locator('.leaflet-popup-content a').click()
    await page.getByRole('heading', { name: 'Explore Pasig', exact: true }).waitFor()
    await page.getByText('Back to Reports', { exact: true }).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('report'), 'reviewed')
    await page.setViewportSize({ width: 320, height: 1000 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.ok((await page.locator('.leaflet-container').boundingBox()).height > 200)
    await page.route('**/api/auth/me', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ user: { full_name: 'Ava Mendoza', avatar_url: `${baseUrl}/images/community/working-together.jpg` } }) }))
    await page.evaluate(() => { localStorage.setItem('authToken', 'synthetic-test-token'); window.dispatchEvent(new Event('ecopin-auth-changed')) })
    await page.locator('header').getByRole('link', { name: 'Open account for Ava Mendoza' }).waitFor()
    await page.evaluate(() => { localStorage.removeItem('authToken'); window.dispatchEvent(new Event('ecopin-auth-changed')) })
    await page.locator('header').getByRole('link', { name: 'Sign in', exact: true }).waitFor()
    await page.goto(`${baseUrl}/explore?report=pending`)
    await page.getByRole('status').filter({ hasText: 'That public report is unavailable.' }).waitFor()
    assert.equal(await page.getByText('Hidden pending concern', { exact: true }).count(), 0)
    assert.deepEqual(errors, [])
    await page.route('**/rest/v1/public_reports*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Unavailable' }) }))
    await page.goto(`${baseUrl}/explore?view=gallery`)
    await page.getByRole('alert').filter({ hasText: 'Reports couldn’t load.' }).waitFor()
    await page.unroute('**/rest/v1/public_reports*')
    await page.getByRole('button', { name: 'Try again', exact: true }).click()
    await page.getByRole('button', { name: 'Reviewed waste concern', exact: true }).waitFor()
    await page.getByLabel('Search gallery reports').fill('no matching concern')
    await page.getByText('No incident photos found', { exact: true }).waitFor()
    assert.deepEqual(errors, [])
    await page.goto(`${baseUrl}/auth`)
    await page.unroute('**/api/auth/login')
    await page.route('**/api/auth/login', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ token: 'synthetic-temporary-token', requirePasswordChange: true }) }))
    await page.getByLabel('Email address').fill('person@example.test')
    await page.getByLabel('Password', { exact: true }).fill('synthetic-password')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.waitForURL('**/force-change-password')
    assert.equal(await page.evaluate(() => localStorage.getItem('authToken')), null)
    assert.equal(await page.evaluate(() => localStorage.getItem('tempAuthToken')), 'synthetic-temporary-token')
    console.log('Public-page browser checks passed: login, canonical routes, modes/history, shared navigation, responsive layouts, landing links, and dark popups.')
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
