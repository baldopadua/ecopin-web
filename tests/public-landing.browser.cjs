// Run against the local preview. Optional bundled Playwright paths are documented
// in docs/public-landing.md; no browser dependency is added to the application.
const assert = require('node:assert/strict')
const { chromium } = require(process.env.ECOPIN_PLAYWRIGHT_PATH || 'playwright')
const baseUrl = process.env.ECOPIN_TEST_URL || 'http://localhost:4001'

async function run() {
  const browser = await chromium.launch({ headless: true, ...(process.env.ECOPIN_CHROMIUM_PATH ? { executablePath: process.env.ECOPIN_CHROMIUM_PATH } : {}) })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/auth/me', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ user: { full_name: route.request().headers().authorization === 'Bearer synthetic-second-token' ? 'Bea Santos' : 'Ava Mendoza', email: 'account@example.test', avatar_url: `${baseUrl}/images/community/working-together.jpg` } }) }))
    await page.addInitScript(() => { localStorage.setItem('authToken', 'synthetic-test-token'); localStorage.setItem('ecopin-motion', 'reduced') })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto(baseUrl)
    await page.getByLabel('Neighborhood', { exact: true }).waitFor()
    await page.waitForFunction(() => !document.querySelector('[role="status"]')?.textContent.includes('Finding public'))
    assert.equal(await page.locator('h1').count(), 1)
    assert.equal(await page.locator('#mobile-app').count(), 1)
    assert.equal(await page.locator('#how-it-works').count(), 1)
    assert.equal(await page.locator('html').evaluate(element => element.classList.contains('lenis')), true)
    await page.getByRole('link', { name: 'Open account for Ava Mendoza' }).waitFor()
    const accountButton = page.locator('header').getByRole('link', { name: 'Open account for Ava Mendoza' })
    assert.equal((await accountButton.innerText()).trim(), '')
    assert.equal(await accountButton.locator('img').count(), 1)
    assert.deepEqual(await page.getByRole('navigation', { name: 'Main navigation' }).locator('a').allTextContents(), ['Home', 'Explore', 'About', 'Download'])
    assert.equal(await page.getByRole('button', { name: /animations/i }).count(), 0)
    await page.evaluate(() => { localStorage.setItem('authToken', 'synthetic-second-token'); window.dispatchEvent(new Event('ecopin-auth-changed')) })
    await page.getByRole('link', { name: 'Open account for Bea Santos' }).waitFor()
    await page.evaluate(() => { localStorage.removeItem('authToken'); window.dispatchEvent(new Event('ecopin-auth-changed')) })
    await page.locator('header').getByRole('link', { name: 'Sign in', exact: true }).waitFor()
    await page.keyboard.press('Tab')
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Skip to content')

    // Native filters stay usable, and the city reset synchronizes the control.
    await page.getByRole('combobox', { name: 'Neighborhood', exact: true }).click()
    await page.getByRole('option', { name: 'Rosario', exact: true }).click()
    await page.getByRole('button', { name: 'Return map to Pasig City' }).click()
    assert.equal((await page.getByRole('combobox', { name: 'Neighborhood', exact: true }).innerText()).trim(), 'All of Pasig')
    await page.getByRole('combobox', { name: 'Concern type', exact: true }).click()
    await page.getByRole('option', { name: 'Waste', exact: true }).click()
    assert.equal((await page.getByRole('combobox', { name: 'Concern type', exact: true }).innerText()).trim(), 'Waste')

    for (const [width, height] of [[320, 900], [768, 1366], [1024, 900], [1440, 1200], [1920, 1500]]) {
      await page.setViewportSize({ width, height })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}px`)
      const mapBounds = await page.getByRole('region', { name: 'Interactive public reports map' }).boundingBox()
      assert.equal(mapBounds.x, 0)
      assert.equal(mapBounds.width, width)
      assert.ok(mapBounds.y + mapBounds.height >= height - 1, 'Map must reach the bottom of the viewport')
      const headerBounds = await page.locator('header').boundingBox()
      assert.equal(headerBounds.x, 0)
      assert.equal(headerBounds.width, width)
    }
    await page.setViewportSize({ width: 320, height: 900 })
    await page.getByRole('button', { name: 'Open navigation' }).click()
    await page.getByRole('link', { name: 'About', exact: true }).click()
    assert.equal(new URL(page.url()).hash, '#about')
    assert.equal(await page.locator('header button[aria-expanded]').getAttribute('aria-expanded'), 'false')
    await page.getByRole('navigation', { name: 'Quick navigation' }).getByRole('link', { name: 'Home', exact: true }).waitFor()
    assert.equal(await page.locator('header').getAttribute('inert'), '')
    const rail = page.getByRole('navigation', { name: 'Quick navigation' })
    assert.deepEqual(await rail.locator('a').evaluateAll(links => links.slice(0, 4).map(link => link.getAttribute('aria-label'))), ['Home', 'Explore', 'About', 'Download App'])

    await page.getByRole('button', { name: 'Switch to dark mode' }).click()
    assert.equal(await page.locator('html').getAttribute('class').then(value => value.includes('dark')), true)
    await page.getByRole('button', { name: 'Switch to light mode' }).click()
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.getByRole('link', { name: 'Explore the map', exact: true }).click()
    await page.getByRole('button', { name: 'Gallery view', exact: true }).waitFor()
    assert.equal(new URL(page.url()).pathname, '/explore')
    await page.waitForFunction(() => !document.documentElement.classList.contains('lenis'))
    assert.equal(await page.locator('html').evaluate(element => element.classList.contains('lenis')), false)
    await page.getByRole('button', { name: 'Gallery view', exact: true }).click()
    assert.equal(new URL(page.url()).pathname, '/explore')
    await page.getByRole('button', { name: 'Map view', exact: true }).click()
    assert.equal(new URL(page.url()).pathname, '/explore')
    await page.getByRole('link', { name: 'Download', exact: true }).click()
    await page.locator('#mobile-app').waitFor()
    assert.equal(new URL(page.url()).pathname, '/')
    assert.equal(new URL(page.url()).hash, '#mobile-app')

    // Exercise both data states without depending on production report contents.
    await page.route('**/rest/v1/public_reports*', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }))
    await page.goto(baseUrl)
    await page.getByRole('status').filter({ hasText: 'No reviewed reports' }).waitFor()
    assert.equal(await page.locator('.leaflet-marker-icon').count(), 0)
    await page.unroute('**/rest/v1/public_reports*')
    await page.route('**/rest/v1/public_reports*', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Unavailable"}' }))
    await page.reload()
    await page.getByRole('button', { name: 'Try again' }).waitFor()
    await page.unroute('**/rest/v1/public_reports*')
    await page.route('**/rest/v1/public_reports*', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }))
    await page.getByRole('button', { name: 'Try again' }).click()
    await page.getByRole('status').filter({ hasText: 'No reviewed reports' }).waitFor()
    await page.unroute('**/rest/v1/public_reports*')
    const fixture = [
      { id: 'reviewed', title: 'Reviewed waste concern', description: 'A public report for the preview check.', validation_status: 'approved', latitude: 14.5802, longitude: 121.085, issue_type: 'waste', status: 'in_progress', location_precision: 'exact' },
      { id: 'unreviewed', title: 'Hidden pending report', validation_status: 'pending', latitude: 14.58, longitude: 121.085 },
      { id: 'no-location', title: 'Hidden report without a location', validation_status: 'approved', latitude: null, longitude: null },
    ]
    await page.route('**/rest/v1/public_reports*', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(fixture) }))
    await page.route('**/api/reports/batch-evidence', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ reviewed: [{ resource_type: 'image', url: `${baseUrl}/images/community/street-cleanup.jpg` }] }) }))
    await page.reload()
    await page.getByRole('status').filter({ hasText: '1 reviewed report' }).waitFor()
    assert.equal(await page.locator('.leaflet-marker-icon').count(), 1)
    await page.locator('.leaflet-marker-icon img').waitFor()
    await page.getByRole('button', { name: 'Reviewed waste concern', exact: true }).click()
    await page.locator('.leaflet-popup').getByText('Status: in progress').waitFor()
    assert.equal(await page.locator('html').evaluate(element => element.classList.contains('lenis')), true)
    await page.getByRole('link', { name: 'About', exact: true }).click()
    await page.waitForFunction(() => !document.documentElement.classList.contains('lenis-scrolling'))
    const storyHeading = page.getByRole('heading', { name: 'From reports to response.' })
    await storyHeading.scrollIntoViewIfNeeded()
    await page.waitForFunction(() => {
      const target = document.getElementById('community-heading').closest('[data-reveal]')
      return target.dataset.revealed === 'true' && getComputedStyle(target).opacity === '1' && !target.getAnimations().length
    })
    const railAccount = page.getByRole('navigation', { name: 'Quick navigation' }).getByRole('link', { name: 'Open account for Ava Mendoza' })
    assert.equal(await railAccount.locator('img').count(), 1)
    assert.equal(await railAccount.locator('img').getAttribute('src'), await page.locator('header a[aria-label="Open account for Ava Mendoza"] img').getAttribute('src'))
    await page.mouse.wheel(0, 1000)
    await page.waitForFunction(() => !document.documentElement.classList.contains('lenis-scrolling'))
    await storyHeading.scrollIntoViewIfNeeded()
    assert.equal(await storyHeading.evaluate(heading => heading.closest('[data-reveal]').getAnimations().length), 0)
    assert.equal(await storyHeading.evaluate(heading => getComputedStyle(heading.closest('[data-reveal]')).opacity), '1')
    await page.waitForFunction(() => [...document.querySelectorAll('img[src*="community"], img[srcset*="community"]')].every(image => image.complete && image.naturalWidth > 0))
    assert.equal(await page.locator('figure').count(), 3)
    await page.getByRole('navigation', { name: 'Quick navigation' }).getByRole('link', { name: 'Home', exact: true }).click()
    await page.locator('header:not([inert])').waitFor()
    await page.waitForFunction(() => Math.abs(document.querySelector('header').getBoundingClientRect().top) < .5)
    assert.equal(Math.round(Math.abs((await page.locator('header').boundingBox()).y)), 0)
    await page.unroute('**/rest/v1/public_reports*')
    await page.route('**/rest/v1/public_reports*', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify([...fixture, { ...fixture[0], id: 'nearby', title: 'Nearby reviewed concern' }]) }))
    await page.reload()
    await page.getByRole('status').filter({ hasText: '2 reviewed reports' }).waitFor()
    assert.equal(await page.locator('.leaflet-marker-icon').count(), 1)
    await page.getByRole('button', { name: 'Nearby reviewed concern', exact: true }).click()
    await page.waitForFunction(() => document.querySelectorAll('.leaflet-marker-icon').length === 2)
    await page.getByRole('button', { name: 'Nearby reviewed concern', exact: true }).waitFor()
    await page.locator('.leaflet-popup').getByText('Status: in progress').waitFor()
    assert.deepEqual(errors, [])
    console.log('Public landing browser checks passed: routes, view modes, filters, theme, menu, responsive widths, empty state, and retry.')
  } finally {
    await browser.close()
  }
}

run().catch(error => { console.error(error); process.exitCode = 1 })
