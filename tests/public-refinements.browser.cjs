const assert = require('node:assert/strict')
const { chromium } = require(process.env.ECOPIN_PLAYWRIGHT_PATH || 'playwright')
const baseUrl = process.env.ECOPIN_TEST_URL || 'http://localhost:4001'
const screenshotDir = process.env.ECOPIN_SCREENSHOT_DIR

async function run() {
  const browser = await chromium.launch({ headless: true, ...(process.env.ECOPIN_CHROMIUM_PATH ? { executablePath: process.env.ECOPIN_CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const reports = [
    { id: 'a', title: 'Waste collection in Rosario', description: 'Waste beside the street in San José.', issue_type: 'waste', validation_status: 'approved', status: 'in_progress', latitude: 14.5802, longitude: 121.085, location_precision: 'exact', created_at: '2026-10-12T12:00:00Z' },
    { id: 'b', title: 'Flooding near the river', description: 'A public flooding concern.', issue_type: 'flooding', validation_status: 'approved', status: 'unresolved', latitude: 14.584, longitude: 121.081, location_precision: 'exact', created_at: '2026-10-11T12:00:00Z' },
  ]
  const photos = ['street-cleanup.jpg', 'neighborhood-team.jpg', 'working-together.jpg'].map((name, index) => ({ resource_type: 'image', name: `Report photo ${index + 1}`, url: `${baseUrl}/images/community/${name}` }))
  await page.addInitScript(() => localStorage.setItem('ecopin_saved_reports', '["a"]'))
  await page.route('**/rest/v1/**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(route.request().url().includes('public_reports') ? reports : []) }))
  await page.route('**/api/**', route => route.fulfill({ contentType: 'application/json', body: '{}' }))
  await page.route('**/api/reports/batch-evidence', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ a: photos, b: [photos[1]] }) }))
  try {
    await page.goto(`${baseUrl}/explore`)
    await page.locator('.leaflet-marker-icon').first().waitFor()
    assert.equal(await page.getByText('Saved Reports', { exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: /export reports|submit a report|save report|bookmark/i }).count(), 0)
    const heading = await page.getByRole('heading', { name: 'Explore Pasig', exact: true }).boundingBox()
    assert.ok(heading.width <= 1 && heading.height <= 1, 'Explore title must remain accessible without a visible title box')
    const map = await page.locator('.leaflet-container').boundingBox()
    assert.ok(map.height > 650)
    assert.ok(Math.abs(map.y + map.height - 1000) < 2, 'Map must use the space freed by the removed footer')
    await page.getByRole('combobox', { name: 'Sort reports', exact: true }).click()
    await page.getByRole('option', { name: 'By status', exact: true }).click()
    assert.match(await page.getByRole('combobox', { name: 'Sort reports', exact: true }).innerText(), /By status/)
    await page.getByRole('button', { name: 'Switch to dark mode' }).click()
    await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-layer')].some(layer => getComputedStyle(layer).filter.includes('invert(1)')))
    await page.locator('.leaflet-marker-icon').first().click()
    await page.locator('.leaflet-popup').waitFor()
    assert.equal(await page.locator('.leaflet-popup').getByRole('button', { name: /save|bookmark/i }).count(), 0)
    const popupFont = await page.locator('.leaflet-popup strong').evaluate(node => getComputedStyle(node).fontFamily)
    assert.match(popupFont, /Outfit/i)
    await page.waitForTimeout(500)
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-explore-map-dark.png` })
    await page.getByRole('button', { name: 'Gallery view', exact: true }).click()
    await page.getByRole('button', { name: 'View photos for Waste collection in Rosario', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: /save|bookmark/i }).count(), 0)
    await page.getByLabel('Search gallery reports').fill('JOSE waste')
    await page.getByRole('status').filter({ hasText: '1 matching report' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Flooding near the river', exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Clear gallery search' }).click()
    await page.getByRole('button', { name: 'Flooding near the river', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Showcase', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Showcase', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.getByRole('button', { name: 'Grid', exact: true }).click()
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-gallery-dark.png` })
    await page.getByRole('button', { name: 'View photos for Waste collection in Rosario', exact: true }).click()
    const viewer = page.getByRole('dialog', { name: 'Report photos' })
    await viewer.waitFor()
    assert.equal(await page.getByText('Inspector', { exact: true }).count(), 0)
    await viewer.getByRole('button', { name: 'Next photo', exact: true }).click()
    await viewer.getByText('Report photo 2', { exact: true }).waitFor()
    await viewer.getByRole('button', { name: 'Previous photo', exact: true }).click()
    await viewer.getByText('Report photo 1', { exact: true }).waitFor()
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-photo-viewer.png` })
    await viewer.getByRole('button', { name: 'Next report', exact: true }).click()
    await viewer.getByRole('heading', { name: 'Flooding near the river', exact: true }).waitFor()
    await page.keyboard.press('Escape')
    await viewer.waitFor({ state: 'hidden' })
    for (const width of [320, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Gallery overflow at ${width}`)
      assert.equal(await page.getByRole('combobox', { name: 'Sort gallery reports' }).locator('span').evaluate(node => node.scrollWidth > node.clientWidth), false, `Gallery sort value must remain readable at ${width}`)
      if (width === 320 && screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-gallery-mobile.png` })
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(baseUrl)
    assert.equal(await page.getByText('For Pasig. For all of us.', { exact: true }).count(), 0)
    await page.locator('.leaflet-marker-icon').first().waitFor()
    await page.locator('.leaflet-marker-icon').first().click()
    assert.equal(await page.locator('.leaflet-popup strong').evaluate(node => getComputedStyle(node).fontFamily), popupFont)
    const before = await page.evaluate(() => scrollY)
    await page.getByRole('combobox', { name: 'Concern type', exact: true }).click()
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    assert.match(await page.getByRole('combobox', { name: 'Concern type', exact: true }).innerText(), /Other concerns/)
    assert.ok(Math.abs(await page.evaluate(() => scrollY) - before) < 2, 'Opening and navigating a dropdown must not jump the page')
    const downloads = []
    page.on('download', download => downloads.push(download))
    const installationHelp = page.getByRole('link', { name: /Need help installing/ })
    await installationHelp.scrollIntoViewIfNeeded()
    await page.waitForFunction(() => [...document.querySelectorAll('[data-reveal]')].filter(node => node.querySelector('a[href="/downloads"]')).every(node => getComputedStyle(node).transform === 'none'))
    await installationHelp.click()
    await page.getByRole('heading', { name: /A little care,\s*right in your pocket/ }).waitFor()
    await page.waitForTimeout(1500)
    assert.equal(downloads.length, 0, 'Installation help must not start an automatic download')
    await page.route('**/ecopin-app-release.apk', route => route.fulfill({ contentType: 'application/vnd.android.package-archive', body: 'synthetic package' }))
    await page.getByText('I can’t find the APK file.', { exact: true }).click()
    assert.equal(await page.locator('details').first().getAttribute('open'), '')
    await page.evaluate(() => { document.activeElement.blur(); scrollTo(0, 0) })
    await page.waitForTimeout(500)
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-downloads-dark.png`, fullPage: true })
    for (const width of [320, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Download help overflow at ${width}`)
    }
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('link', { name: 'Download for Android', exact: true }).click()
    await downloadEvent
    assert.ok(downloads.length > 0)
    await page.goto(`${baseUrl}/auth`)
    await page.getByRole('heading', { name: 'Welcome back.' }).waitFor()
    assert.equal(await page.getByRole('navigation').count(), 0)
    assert.equal(await page.getByText(/Behind every response/).count(), 0)
    assert.equal(await page.getByRole('heading', { name: /A little care/ }).count(), 0)
    await page.getByRole('button', { name: 'Pause slideshow' }).waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('main img')].some(image => image.complete && image.naturalWidth > 0 && image.getAttribute('aria-hidden') === 'false'))
    await page.waitForTimeout(1600)
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-auth-dark.png`, fullPage: true })
    await page.setViewportSize({ width: 320, height: 900 })
    await page.waitForFunction(() => document.querySelectorAll('main img').length === 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refined-auth-mobile.png`, fullPage: true })
    await page.getByRole('link', { name: 'Back to EcoPin', exact: true }).click()
    await page.getByRole('heading', { name: /A cleaner Pasig/ }).waitFor()
    assert.deepEqual(errors, [])
    const cyclePage = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    await cyclePage.clock.install()
    await cyclePage.goto(`${baseUrl}/auth`)
    await cyclePage.getByRole('button', { name: 'Pause slideshow' }).click()
    const current = await cyclePage.locator('[aria-label^="Photo "]').getAttribute('aria-label')
    await cyclePage.clock.fastForward(16000)
    assert.equal(await cyclePage.locator('[aria-label^="Photo "]').getAttribute('aria-label'), current)
    await cyclePage.getByRole('button', { name: 'Play slideshow' }).click()
    await cyclePage.clock.fastForward(8000)
    assert.notEqual(await cyclePage.locator('[aria-label^="Photo "]').getAttribute('aria-label'), current)
    await cyclePage.clock.fastForward(8000)
    await cyclePage.clock.fastForward(8000)
    assert.equal(await cyclePage.locator('[aria-label^="Photo "]').getAttribute('aria-label'), current)
    await cyclePage.close()
    console.log('Public refinements passed: removed features, view placement, themed map/popups, controls/search, photo navigation, downloads, auth/mobile and slow slideshow.')
  } catch (error) {
    console.error('Failure page:', page.url(), 'Headings:', await page.locator('h1,h2').allTextContents())
    if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/refinements-failure.png`, fullPage: true })
    throw error
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
